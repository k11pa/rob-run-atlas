import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const source = fs.readFileSync('dist/app.js', 'utf8');
const render = source.split('\n').find(line => line.trimStart().startsWith('function lootDetail('));
if (!render) throw Error('lootDetail not found');
const context = {price: v => new Intl.NumberFormat('ru-RU').format(v)};
vm.createContext(context);
vm.runInContext(render, context);
const base = {amountMin: 1, amountMax: 1};
assert.equal(context.lootDetail(base), '×1');
assert.equal(context.lootDetail({...base, probability: null}), '×1');
assert.equal(context.lootDetail({...base, probability: 0}), '×1 · 0% за выбор');
assert.equal(context.lootDetail({...base, probability: 1}), '×1 · 100% за выбор');
assert.equal(context.lootDetail({...base, probability: 0.125}), '×1 · 12,5% за выбор');
assert.equal(context.lootDetail({...base, stepsMin: 9, stepsMax: 9}), 'за действие ×1 · действий: 9');
assert.equal(context.lootDetail({...base, amountMax: 3, stepsMin: 2, stepsMax: 5}), 'за действие ×1–3 · действий: 2–5');
assert.equal(context.lootDetail({...base, weight: 5}), '×1 · вес 5');
console.log('Probability rendering OK: unknown/null, zero, 100%, fraction, quantities/actions, weight.');
